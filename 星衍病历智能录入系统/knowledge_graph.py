    def _add_relation(self, subj, rel, obj):
        """追加关系并去重（内置 + 外部统一入口）"""
        if not subj or not obj:
            return
        triple = (subj, rel, obj)
        if triple in self._rel_set:
            return
        self._rel_set.add(triple)
        self.relations.append(triple)
        # 维护正/反向索引
        self._rel_by_subj.setdefault(subj, []).append((rel, obj))
        self._rel_by_obj.setdefault(obj, []).append((rel, subj))

    def query_by_subj(self, subj, rel=None):
        """正向查询：给定主体，返回 [(rel, obj)] 或过滤后的 [obj]"""
        pairs = self._rel_by_subj.get(subj, [])
        if rel:
            return [o for r, o in pairs if r == rel]
        return pairs

    def query_by_obj(self, obj, rel=None):
        """反向查询：给定客体，返回 [(rel, subj)] 或过滤后的 [subj]"""
        pairs = self._rel_by_obj.get(obj, [])
        if rel:
            return [s for r, s in pairs if r == rel]
        return pairs

    def _merge_entity(self, name, info):
        """合并一个实体到图谱：新增则登记，已存在则并入列表字段"""
        etype = info.get("type")
        if name not in self.entities:
            self.entities[name] = dict(info)
            if etype:
                self.entity_types[name] = etype
            return
        # 已存在：合并列表型字段（症状/检查/药物等），标量字段保留原值
        existing = self.entities[name]
        for key, val in info.items():
            if isinstance(val, list):
                merged = existing.get(key, [])
                for item in val:
                    if item not in merged:
                        merged.append(item)
                existing[key] = merged
            elif key not in existing or not existing.get(key):
                existing[key] = val

    def _load_external_kg(self):
        """
        从 self.external_dir 加载 *.json 外部医学知识并合并进图谱。
        统一 schema（详见 kg_data/README）：
            {
              "source": "OpenKG-CMeKG",
              "diseases": {"疾病名": {"系统":..., "常见症状":[...],
                            "常见检查":[...], "常用药物":[...], "别名":[...]}},
              "drugs":    {"药物名": {"类别":..., "关联疾病":[...],
                            "说明书": {"适应症":..., "用法用量":..., "禁忌":..., "不良反应":...}}}
            }
        无目录 / 无文件 / 单文件损坏都不会影响内置图谱可用性。
        返回本次导入的实体数量。
        """
        loaded = 0
        if not os.path.isdir(self.external_dir):
            return loaded
        try:
            files = sorted(f for f in os.listdir(self.external_dir)
                           if f.endswith(".json"))
        except OSError:
            return loaded
        for fname in files:
            fpath = os.path.join(self.external_dir, fname)
            try:
                with open(fpath, "r", encoding="utf-8") as fh:
                    data = json.load(fh)
            except (OSError, ValueError):
                # 单个文件损坏不影响其余，跳过
                continue
            loaded += self._merge_kg_payload(data)
        return loaded

    def _merge_kg_payload(self, data):
        """合并一份已解析的 JSON 知识载荷，返回新增/更新实体数"""
        if not isinstance(data, dict):
            return 0
        # 三元组格式（xywy_kg.json 等）：{"meta":..., "entities":[...], "triples":[{"s","p","o"}]}
        if "triples" in data and "entities" in data:
            return self._merge_triples_payload(data)
        count = 0
        for name, info in (data.get("diseases") or {}).items():
            info = dict(info or {})
            info.setdefault("type", "疾病")
            self._merge_entity(name, info)
            for alias in info.get("别名", []):
                self.aliases[alias] = name
            for symptom in info.get("常见症状", []):
                self._add_relation(name, "HAS_SYMPTOM", symptom)
                self._add_relation(symptom, "INDICATES", name)
                self.entity_types.setdefault(symptom, "症状")
            for exam in info.get("常见检查", []):
                self._add_relation(name, "HAS_EXAM", exam)
                self.entity_types.setdefault(exam, "检查")
            for drug in info.get("常用药物", []):
                self._add_relation(name, "TREATED_BY", drug)
                self._add_relation(drug, "TREATS", name)
                self.entity_types.setdefault(drug, "药物")
            count += 1
        for name, info in (data.get("drugs") or {}).items():
            info = dict(info or {})
            info.setdefault("type", "药物")
            insert = info.pop("说明书", None)
            self._merge_entity(name, info)
            for alias in info.get("别名", []):
                self.aliases[alias] = name
            for disease in info.get("关联疾病", []):
                self._add_relation(name, "TREATS", disease)
                self._add_relation(disease, "TREATED_BY", name)
            if insert:
                self.drug_inserts[name] = insert
            count += 1
        # 食物实体（DiseaseKG 饮食宜忌）
        for name, info in (data.get("foods") or {}).items():
            info = dict(info or {})
            info.setdefault("type", "食物")
            self._merge_entity(name, info)
            for disease in info.get("关联疾病", []):
                self._add_relation(name, "FOOD_FOR", disease)
                self._add_relation(disease, "RECOMMEND_FOOD", name)
            count += 1
        return count

    def _merge_triples_payload(self, data):
        """
        合并三元组格式的知识图谱（xywy-KG 等）。
        格式: {"entities": [...], "triples": [{"s": 主体, "p": 关系, "o": 客体}]}
        关系映射: 症状→HAS_SYMPTOM, 推荐药物→TREATED_BY, 检查项目→HAS_EXAM,
                  就诊科室→BELONGS_TO, 并发疾病→COMPLICATES, 治疗方式→TREATED_BY
        """
        # 关系名 → (内部关系, 客体类型)
        rel_map = {
            "症状": ("HAS_SYMPTOM", "症状"),
            "并发疾病": ("COMPLICATES", "疾病"),
            "推荐药物": ("TREATED_BY", "药物"),
            "检查项目": ("HAS_EXAM", "检查"),
            "就诊科室": ("BELONGS_TO", "科室"),
            "治疗方式": ("TREATED_BY", "治疗"),
            "属于科室": ("BELONGS_TO", "科室"),
            "预防": ("PREVENTED_BY", "预防"),
            "病因": ("CAUSED_BY", "病因"),
        }
        # 先注册所有实体为疾病（三元组中 subject 通常是疾病）
        count = 0
        for entity_name in data.get("entities", []):
            if entity_name and entity_name not in self.entities:
                self.entities[entity_name] = {"type": "疾病", "source": "xywy-KG"}
                self.entity_types.setdefault(entity_name, "疾病")
                count += 1
        # 处理三元组
        for tri in data.get("triples", []):
            s, p, o = tri.get("s", ""), tri.get("p", ""), tri.get("o", "")
            if not s or not o:
                continue
            mapping = rel_map.get(p)
            if not mapping:
                continue
            internal_rel, obj_type = mapping
            self._add_relation(s, internal_rel, o)
            self.entity_types.setdefault(o, obj_type)
            # 反向关系
            if internal_rel == "HAS_SYMPTOM":
                self._add_relation(o, "INDICATES", s)
            elif internal_rel == "TREATED_BY":
                self._add_relation(o, "TREATS", s)
        print(f"[KG] 三元组导入: {count} 实体, {len(data.get('triples', []))} 关系")
        return count

    def normalize(self, name):
        """把别名归一化到标准实体名（无别名时原样返回）"""
        return self.aliases.get(name, name)

    def _load_drug_inserts(self):
        """加载批量下载的药品说明书（kg_data/drug_inserts.json）"""
        path = os.path.join(self.external_dir, "drug_inserts.json")
        if not os.path.exists(path):
            return
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            count = 0
            for name, info in data.items():
                if name and isinstance(info, dict) and name not in self.drug_inserts:
                    self.drug_inserts[name] = info
                    count += 1
            if count:
                print(f"[KG] 药品说明书加载: {count} 种 (总计 {len(self.drug_inserts)})")
        except Exception as e:
            print(f"[KG] 加载药品说明书失败: {e}")

    def get_drug_info(self, drug):
        """返回药物说明书信息（适应症/用法用量/禁忌/不良反应），无则 None"""
        drug = self.normalize(drug)
        # 精确匹配
        if drug in self.drug_inserts:
            return self.drug_inserts[drug]
        # 模糊匹配：说明书键包含该药名（如"氨氯地平"→"苯磺酸氨氯地平片"）
        if len(drug) >= 3:
            candidates = [(k, v) for k, v in self.drug_inserts.items() if drug in k]
            if candidates:
                # 取最短的匹配（最接近通用名）
                candidates.sort(key=lambda x: len(x[0]))
                return candidates[0][1]
        return None

    def recommend_treatment(self, disease):
        """
        综合治疗方案推荐：整合西医药物 + 检查 + 中医证型 + 饮食宜忌，
        并附带药物说明书（若有）。返回结构化 dict。
        """
        disease = self.normalize(disease)
        drugs = self.get_drugs_for_disease(disease)
        result = {
            "disease": disease,
            "exists": disease in self.entities,
            "常用药物": drugs,
            "常见检查": self.get_exams_for_disease(disease),
            "常见症状": self.get_symptoms_for_disease(disease),
            "危急值": self.get_critical_value(disease),
            "药物说明书": {d: self.drug_inserts[d] for d in drugs
                          if d in self.drug_inserts},
            "中医证型": self.get_syndromes_for_disease(disease),
            "饮食宜忌": self.get_diet_for_disease(disease),
        }
        return result

