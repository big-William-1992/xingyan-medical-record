    def get_related_entities(self, entity_name, relation=None):
        """获取关联实体"""
        related = []
        for subj, rel, obj in self.relations:
            if subj == entity_name:
                if relation is None or rel == relation:
                    related.append((rel, obj))
            elif obj == entity_name:
                if relation is None or rel == relation:
                    related.append((rel, subj))
        return related

